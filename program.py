# Arithmetic Operators in Python

# 1. Addition (+)
print("Addition")
print("10 + 5 =", 10 + 5)
print("2.5 + 3.5 =", 2.5 + 3.5)

# 2. Subtraction (-)
print("\nSubtraction")
print("20 - 8 =", 20 - 8)
print("5 - 12 =", 5 - 12)

# 3. Multiplication (*)
print("\nMultiplication")
print("6 * 7 =", 6 * 7)
print("2.5 * 4 =", 2.5 * 4)

# 4. Division (/) - returns a float
print("\nDivision")
print("20 / 4 =", 20 / 4)
print("7 / 2 =", 7 / 2)

# 5. Floor Division (//) - rounds the result down
print("\nFloor Division")
print("17 // 5 =", 17 // 5)
print("-17 // 5 =", -17 // 5)

# 6. Modulus (%) - returns the remainder
print("\nModulus")
print("17 % 5 =", 17 % 5)
print("20 % 4 =", 20 % 4)

# 7. Exponentiation (**) - power
print("\nExponentiation")
print("2 ** 3 =", 2 ** 3)
print("5 ** 2 =", 5 ** 2)


# Assignment Operators in Python

# 1. Assign (=)
print("Assign (=)")
a = 10
print("a = 10 ->", a)
name = "Python"
print('name = "Python" ->', name)

# 2. Add and assign (+=)
print("\nAdd Assign (+=)")
a = 10
a += 5
print("a = 10; a += 5 ->", a)
b = 2.5
b += 1.5
print("b = 2.5; b += 1.5 ->", b)

# 3. Subtract and assign (-=)
print("\nSubtract Assign (-=)")
a = 20
a -= 8
print("a = 20; a -= 8 ->", a)
b = 5
b -= 12
print("b = 5; b -= 12 ->", b)

# 4. Multiply and assign (*=)
print("\nMultiply Assign (*=)")
a = 6
a *= 7
print("a = 6; a *= 7 ->", a)
b = 2.5
b *= 4
print("b = 2.5; b *= 4 ->", b)

# 5. Divide and assign (/=)
print("\nDivide Assign (/=)")
a = 20
a /= 4
print("a = 20; a /= 4 ->", a)
b = 7
b /= 2
print("b = 7; b /= 2 ->", b)

# 6. Floor divide and assign (//=)
print("\nFloor Divide Assign (//=)")
a = 17
a //= 5
print("a = 17; a //= 5 ->", a)
b = -17
b //= 5
print("b = -17; b //= 5 ->", b)

# 7. Modulus and assign (%=)
print("\nModulus Assign (%=)")
a = 17
a %= 5
print("a = 17; a %= 5 ->", a)
b = 20
b %= 4
print("b = 20; b %= 4 ->", b)

# 8. Power and assign (**=)
print("\nPower Assign (**=)")
a = 2
a **= 3
print("a = 2; a **= 3 ->", a)
b = 5
b **= 2
print("b = 5; b **= 2 ->", b)